def test_fixture_catalog_retains_documentary_scope_and_new_generation_provenance(tmp_path):
    account = transport.Account(tmp_path / "fixture", **transport.LIMITS)
    payload = b'{"schema":"original-supervisor-test-fixture","value":2}\n'
    request_path, received = transport.prepare_transport(account, payload, Path("/original-test-binary"), "1" * 64, "2" * 64)
    request = json.loads(request_path.read_bytes())
    contract = json.loads((account.root / "contract.json").read_bytes())
    entry = json.loads((account.root / "source/catalog.json").read_bytes())["entries"][0]
    review = json.loads((account.root / "publication-record.json").read_bytes())
    assert entry["checker"] is None and entry["geometry_lineage"] is None and entry["evidence"] == []
    assert entry["home"] == "logic" and entry["recorded_status"] == "proposed-document"
    assert contract["profile"] == "documentary-library-entry-v1"
    assert contract["entry_blake3"] == transport.b3(json.dumps(entry, ensure_ascii=False, sort_keys=True, separators=(",", ":")).encode())
    assert contract["files"][0]["blake3"] == transport.b3(payload)
    assert request["acknowledgment"] is None and request["structure_member"] is None
    assert "newly generated bytes did not exist" in review["provenance"]["transformations"][0]["base_revision_scope"]
    assert not received.exists()


