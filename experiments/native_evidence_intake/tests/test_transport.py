def test_real_transport_then_separate_native_check_preserves_receipt(binaries, outside_root):
    report, code = transport.run(*binaries, outside_root)
    assert code == 0, report
    assert report["status"] == "CompletedSeparateNativeCheck"
    assert report["aggregate_native_calls"] == 7
    assert [value["status"] for value in report["transport"]["observations"]] == [
        "Sent", "AcceptedDocumentary", "AlreadyAccepted", "Acknowledged"]
    assert report["transport"]["observations"][2]["acceptance_effects"] == 0
    before = (outside_root / "receipt-before-native.json").read_bytes()
    after = (outside_root / "receipt-after-native.json").read_bytes()
    assert before == after == Path(report["receipt_path"]).read_bytes()
    receipt = json.loads(before)
    assert receipt["semantic_verification"] == "NotRun" and receipt["native_admission"] == "NotGranted"
    assert (outside_root / "source" / transport.SOURCE_MEMBER).read_bytes() == Path(report["received_evidence_path"]).read_bytes()
    assert not (Path(report["receipt_path"]).parent / "native-report.json").exists()
    assert (outside_root / "native-report.json").is_file()
    assert json.loads((outside_root / "result.json").read_bytes()) == report


@pytest.mark.parametrize("field", ["name", "context"])
def test_changed_supplied_receiver_or_context_stops_before_native_check(binaries, outside_root, monkeypatch, field):
    original = transport.execute_transport

    def changed_request(path, expected, output):
        request = json.loads(path.read_bytes())
        request["receiver"][field] = "wrong-receiver-context"
        path.write_bytes(transport.encoded(request))
        # This is an explicitly different independently pinned request, not a
        # stale request digest. The existing contract must still reject it.
        return original(path, transport.sha(path.read_bytes()), output)

    monkeypatch.setattr(transport, "execute_transport", changed_request)
    report, code = transport.run(*binaries, outside_root)
    assert code == 2, report
    assert report["transport"]["status"] == "Refused"
    assert report["transport"]["cost"]["native_calls"] == 0
    assert report["native_check"] == "NotRun"
    assert report["aggregate_native_calls"] == 2
    assert not (outside_root / "native-check.stdout.txt").exists()
    assert list((outside_root / "store").iterdir()) == []


