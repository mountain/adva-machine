def test_independent_native_rejection_after_delivery_preserves_documentary_scope(binaries, outside_root, monkeypatch):
    original = transport.child_json

    def changed_native_context(account, label, command, limit):
        if label == "native-check":
            command = list(command)
            command[-1] = "wrong-independent-native-context"
        return original(account, label, command, limit)

    monkeypatch.setattr(transport, "child_json", changed_native_context)
    report, code = transport.run(*binaries, outside_root)
    assert code == 2, report
    assert report["transport"]["status"] == "CompletedDocumentaryExchange"
    assert report["native_check"]["outcome"] == "Rejected"
    assert report["native_check"]["local_check_and_cache"] is None
    assert report["aggregate_native_calls"] == 7
    before = (outside_root / "receipt-before-native.json").read_bytes()
    after = (outside_root / "receipt-after-native.json").read_bytes()
    assert before == after == Path(report["receipt_path"]).read_bytes()
    receipt = json.loads(after)
    assert receipt["semantic_verification"] == "NotRun" and receipt["native_admission"] == "NotGranted"
    acknowledgment = json.loads(Path(report["acknowledgment_path"]).read_bytes())
    assert acknowledgment["receipt_blake3"] == transport.b3(before)
    assert acknowledgment["semantic_verification"] == "NotRun" and acknowledgment["native_admission"] == "NotGranted"
    assert (outside_root / "source" / transport.SOURCE_MEMBER).read_bytes() == Path(report["received_evidence_path"]).read_bytes()
    assert (outside_root / "native-report.json").is_file()


def test_receipt_mutation_after_transport_is_refused_before_native_check(binaries, outside_root, monkeypatch):
    original = transport.execute_transport

    def change_receipt_after_completed_transport(path, expected, output):
        result, code = original(path, expected, output)
        assert code == 0, result
        receipt_path = Path(result["receiver_receipt_path"])
        receipt = json.loads(receipt_path.read_bytes())
        receipt["residual"] += " Original negative-control mutation after completed transport."
        assert receipt["semantic_verification"] == "NotRun" and receipt["native_admission"] == "NotGranted"
        receipt_path.write_bytes(transport.encoded(receipt))
        return result, code

    monkeypatch.setattr(transport, "execute_transport", change_receipt_after_completed_transport)
    report, code = transport.run(*binaries, outside_root)
    assert code == 2, report
    assert report["status"] == "Refused"
    assert report["transport"]["status"] == "CompletedDocumentaryExchange"
    assert report["transport_receipt_mutated"] is True
    assert report["native_check"] == "NotRun"
    assert report["aggregate_native_calls"] == 6
    assert "receipt pin" in report["reason"]
    assert not (outside_root / "native-check.stdout.txt").exists()
    observed = (outside_root / "receipt-before-native.json").read_bytes()
    assert transport.b3(observed) != report["transport"]["receipt_blake3"]
    receipt = json.loads(observed)
    assert receipt["semantic_verification"] == "NotRun" and receipt["native_admission"] == "NotGranted"
